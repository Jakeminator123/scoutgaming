-- Additive native-table slice only; not yet the full product schema.
-- Apply only to a separate, empty game Neon database in an isolated test.
CREATE TABLE players (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  currency TEXT NOT NULL DEFAULT 'USD',
  balance NUMERIC(18,2) NOT NULL DEFAULT 1000,
  created_at TEXT NOT NULL
);

CREATE TABLE transactions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  player_id TEXT NOT NULL,
  type TEXT NOT NULL,
  amount NUMERIC(18,2) NOT NULL,
  currency TEXT NOT NULL,
  meta TEXT,
  at TEXT NOT NULL
);
CREATE INDEX transactions_player_id_id ON transactions (player_id, id);

CREATE TABLE blackjack_tables (
  player_id TEXT PRIMARY KEY,
  state TEXT NOT NULL
);

CREATE TABLE native_presentations (
  player_id TEXT PRIMARY KEY,
  request_id TEXT NOT NULL,
  version INTEGER NOT NULL,
  payload TEXT NOT NULL
);
