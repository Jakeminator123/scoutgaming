"""Measure the visible white prop in each decoded source frame (24 fps).
Requires OpenCV + numpy + Pillow. Writes finite per-frame pose/occlusion data;
never processes or changes dealer media or server cards.
"""
import cv2, numpy as np, json, hashlib
from PIL import Image, ImageDraw
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
manifest=json.loads((ROOT/'public/media/manifest.json').read_text())
FIRST={'1':51,'2':44,'3':47,'4':47,'5':43,'6':41,'7':44,'dealer':37}
tracks={}; metrics={}
for clip in manifest['deal']:
 seat=clip['id'].replace('deal_pos','');cx,cy=clip['kort']['cx'],clip['kort']['cy']
 path=ROOT/('public'+clip['url']); cap=cv2.VideoCapture(str(path))
 ox=max(0,min(820,cx-130));oy=cy-230
 frames=[]; samples=[];f=0
 while True:
  ok,bgr=cap.read()
  if not ok:break
  if f<FIRST[seat]:f+=1;continue
  roi=bgr[oy:oy+300,ox:ox+260]; rgb=cv2.cvtColor(roi,cv2.COLOR_BGR2RGB)
  r,g,b=rgb.astype(float).transpose(2,0,1)
  neutral=.995 if seat=='dealer' else .92
  mask=((np.minimum(np.minimum(r,g),b)>70)&(b>=r*neutral)&(g>=r*neutral)).astype('uint8')*255
  # Keep the card, not isolated cream table typography or skin highlights.
  contours,_=cv2.findContours(mask,cv2.RETR_EXTERNAL,cv2.CHAIN_APPROX_SIMPLE)
  valid=[]
  for cnt in contours:
   area=cv2.contourArea(cnt);x,y,w,h=cv2.boundingRect(cnt)
   if area>60 and h>12 and abs(x+w/2-(cx-ox))<105 and y>55:valid.append(cnt)
  if not valid and seat in ('6','7') and f==FIRST[seat]:
   # The initial thin, motion-blurred face is warm from finger spill. Its edge
   # is manually bounded so the hand can never become part of the paper mask.
   bounds={'6':[[157,164],[169,161],[166,224],[156,241]],'7':[[148,143],[161,128],[157,203],[148,221]]}
   valid=[np.array(bounds[seat],dtype='int32').reshape(-1,1,2)]
  if not valid:raise ValueError(f'No card {seat} f{f}')
  cnt=max(valid,key=cv2.contourArea); hull=cv2.convexHull(cnt)
  quad=None
  for e in np.arange(.008,.085,.002):
   approx=cv2.approxPolyDP(hull,e*cv2.arcLength(hull,True),True)
   if len(approx)==4:quad=approx[:,0,:].astype(float);break
  if quad is None:quad=cv2.boxPoints(cv2.minAreaRect(hull))
  # Cyclic TL/TR/BR/BL; the rank remains at the same physical corner.
  center=quad.mean(axis=0);quad=quad[np.argsort(np.arctan2(quad[:,1]-center[1],quad[:,0]-center[0]))]
  quad=np.roll(quad,-np.argmin(quad.sum(axis=1)),axis=0)
  contour=cv2.approxPolyDP(cnt,.65,True)[:,0,:]
  body=(contour+[ox-cx,oy-cy]).tolist()
  if f>=FIRST[seat]+2:
   # Thumb notches must not become a geometric card corner. Fit the complete
   # rigid rectangular extent; the separate visible contour still masks fingers.
   quad=cv2.boxPoints(cv2.minAreaRect(hull)).astype(float)
   center=quad.mean(axis=0);quad=quad[np.argsort(np.arctan2(quad[:,1]-center[1],quad[:,0]-center[0]))]
   quad=np.roll(quad,-np.argmin(quad.sum(axis=1)),axis=0)
  # Single-pixel inward contour keeps ink off motion-blurred fingers.
  cm=np.zeros(mask.shape,'uint8');cv2.drawContours(cm,[cnt],-1,255,-1)
  cm=cv2.erode(cm,np.ones((3,3),np.uint8))
  contours2,_=cv2.findContours(cm,cv2.RETR_EXTERNAL,cv2.CHAIN_APPROX_SIMPLE)
  if contours2:contour=cv2.approxPolyDP(max(contours2,key=cv2.contourArea),.65,True)[:,0,:]
  q=np.round(quad+[ox-cx,oy-cy],2).tolist();p=(contour+[ox-cx,oy-cy]).tolist()
  pixels=rgb[cm>0]
  paper=np.median(pixels,axis=0).round().astype(int).tolist()
  frames.append({'q':q,'p':p,'body':body,'paper':paper})
  if f in [FIRST[seat],FIRST[seat]+1,FIRST[seat]+2,FIRST[seat]+4,FIRST[seat]+9,FIRST[seat]+15]:
   im=Image.fromarray(rgb);d=ImageDraw.Draw(im);d.line([tuple(v) for v in quad]+[tuple(quad[0])],fill='#00ffaa',width=1);d.line([tuple(v) for v in contour]+[tuple(contour[0])],fill='#ff6677',width=1);d.text((4,4),f'{seat} frame {f}',fill='red');samples.append(im)
  f+=1
 # Symmetric local quadratic smoothing removes segmentation jitter without a
 # playback delay. Only pose is smoothed; source-frame finger masks are exact.
 raw=np.array([frame['q'] for frame in frames],dtype=float)
 for i in range(4,len(frames)):
  lo=max(2,i-2);hi=min(len(frames),i+3)
  t=np.arange(lo,hi)-i
  design=np.stack([np.ones_like(t),t,t*t],axis=1).astype(float)
  weights=np.linalg.pinv(design)[0]
  frames[i]['q']=np.round(np.tensordot(weights,raw[lo:hi],axes=(0,0)),3).tolist()
 tracks[seat]={'firstFrame':FIRST[seat],'frames':frames}
 metrics[seat]={'firstWhiteFrame':FIRST[seat],'sourceFrames':f,'sha256':hashlib.sha256(path.read_bytes()).hexdigest(),'restQuad':frames[-1]['q']}
 sheet=Image.new('RGB',(260*3,300*2),'#222')
 for i,im in enumerate(samples):sheet.paste(im,((i%3)*260,(i//3)*300))
 sheet.save(ROOT/f'review/2026-09-25-card-faces/seat-{seat}.jpg',quality=88)
(ROOT/'public/card-face-tracks.js').write_text('// Generated by review/2026-09-25-card-faces/build-tracks.py.\n// Source-frame coordinates relative to the manifest landing center.\nexport const CARD_FACE_TRACKS = '+json.dumps(tracks,separators=(',',':'))+';\n')
(ROOT/'review/2026-09-25-card-faces/measurements.json').write_text(json.dumps(metrics,indent=2)+'\n')
print(json.dumps(metrics,indent=2))
