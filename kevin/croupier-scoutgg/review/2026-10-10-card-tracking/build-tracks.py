"""Card tracks for a ready dealer (Kevin 10 Oct: "korten ser helt fel, vi behöver bättre motion tracking").

Mocha-style planar tracking: per take, the filmed white card is followed as a plane (four corners, a homography per
frame), starting on the landed card (its clearest frame) and walking BACKWARDS through the throw (planar_track.py).
Writes <public>/dealer-card-tracks-<id>.js (q = the corner pin, p/body = the whole face: his keyed fingers lie on top)
and prints each take's landing frame (the card no longer moves) for dealers.js.
Usage: python build-tracks.py <public dir> <dealer id>   (reads <public>/media/dealers/<id>/v2/<take>.mp4)
Kevin's review (10 Oct): the first in-hand frames of Dragge 5/6 and Mårten 5/6/7/dealer drift off the card while the
fingers hold it edge-on; those tracks start 2-3 frames later in the committed files.
"""
import json, os, sys
import numpy as np
from planar_track import load, track, planar, classes, cv2

PUB, DID = sys.argv[1:3]
manifest = json.load(open(os.path.join(PUB, 'media/manifest.json')))
CENTRE = {d['id'].replace('deal_pos', '').replace('deal_', ''): (d['kort']['cx'], d['kort']['cy']) for d in manifest['deal']}
tracks, land = {}, {}
for k in ['1', '2', '3', '4', '5', '6', '7', 'dealer', '1v', '2v', '3v', '4v', '5v', '6v', '7v', 'dealerv', 'flip']:
    take = 'flip' if k == 'flip' else ('posdealer' if k.startswith('dealer') else 'pos' + k[0]) + ('-v' if k.endswith('v') else '')
    cx, cy = CENTRE['dealer' if k in ('flip', 'dealerv') else k.rstrip('v')]
    fr = load(os.path.join(PUB, f'media/dealers/{DID}/v2/{take}.mp4')); n = len(fr)
    det = {f: v[0] for f, v in track(fr, cx, cy)[0].items()}
    pl = planar(fr, det, det[n - 1]); first = min(pl)
    def paper(f, q):
        m = np.zeros(fr[f].shape[:2], np.uint8); cv2.fillPoly(m, [np.round(q).astype(np.int32)], 1); m = m.astype(bool) & classes(fr[f])
        return np.median(fr[f][m][:, ::-1], axis=0).round().astype(int).tolist() if m.sum() > 50 else [235, 235, 235]
    rel = lambda q: [[round(float(x) - cx, 2), round(float(y) - cy, 2)] for x, y in q]
    tracks[k] = {'firstFrame': first, 'frames': [{'q': rel(pl[f]), 'p': rel(pl[f]), 'body': rel(pl[f]), 'paper': paper(f, pl[f])} for f in range(first, n)]}
    gl = n - 1
    while gl - 1 in pl and np.linalg.norm(pl[gl - 1] - pl[n - 1], axis=1).mean() < 1.0: gl -= 1
    land[k] = gl
    print(f'{k:8s} {take:12s} face-up {first:2d}  rests {gl:2d}')
open(os.path.join(PUB, f'dealer-card-tracks-{DID}.js'), 'w').write(
    '// Generated by review/2026-10-10-card-tracking/build-tracks.py: a planar (corner pin) track of his filmed card, walked back\n'
    '// from the landed card with ECC homographies; same format as card-face-tracks.js. Screen coordinates relative to the\n'
    "// manifest landing centre, in the deal take's own frames (no in-transition). p/body are the whole face: his keyed fingers lie on top.\n"
    f'export const {DID.upper()}_FACE_TRACKS = ' + json.dumps(tracks, separators=(',', ':')) + ';\n')
print('land', json.dumps(land, separators=(',', ':')))
