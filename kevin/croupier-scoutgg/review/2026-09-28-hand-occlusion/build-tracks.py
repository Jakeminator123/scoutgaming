"""Measure Astrid's hands over the dealer-card area from original source frames.
Offline calibration only: no media changes or runtime pixel processing.
Run with Python + OpenCV + numpy + Pillow.
"""
import cv2, numpy as np, json, hashlib
from pathlib import Path
from PIL import Image, ImageDraw
ROOT=Path(__file__).resolve().parents[2]
OUT=Path(__file__).resolve().parent
manifest=json.loads((ROOT/'public/media/manifest.json').read_text())
# Includes the bounded dealer fan and its moving incoming card. Player hands
# settle below this region. Keep the table lettering out of the skin contour.
X,Y,W,H=300,790,400,170
tracks={};metrics={};samples=[]
for clip in manifest['deal']:
 seat=clip['id'].replace('deal_pos','')
 path=ROOT/('public'+clip['url']); cap=cv2.VideoCapture(str(path))
 frames=[];f=0
 while True:
  ok,bgr=cap.read()
  if not ok:break
  rgb=cv2.cvtColor(bgr[Y:Y+H,X:X+W],cv2.COLOR_BGR2RGB)
  r,g,b=rgb.astype(float).transpose(2,0,1)
  skin=((r>35)&(g>20)&(r-g>9)&(r-b>15)&(g>b*.90)).astype('uint8')*255
  # Close tiny codec holes, then retain actual hand components, not isolated
  # warm lettering pixels. One pixel dilation protects the filmed soft edge.
  skin=cv2.morphologyEx(skin,cv2.MORPH_CLOSE,np.ones((3,3),np.uint8))
  cs,_=cv2.findContours(skin,cv2.RETR_EXTERNAL,cv2.CHAIN_APPROX_SIMPLE)
  mask=np.zeros_like(skin)
  for c in cs:
   x,y,w,h=cv2.boundingRect(c)
   # A wrist/arm enters this narrow band from above or the side. Isolated
   # warm table text and the gold prop border are not part of her hand.
   if cv2.contourArea(c)>=65 and (y==0 or x==0 or x+w==W):
    cv2.drawContours(mask,[c],-1,255,-1)
  mask=cv2.dilate(mask,np.ones((3,3),np.uint8))
  # Only existing dealer cards need this extra occlusion pass. Incoming face
  # projection already protects its fingers. Clip to the full bounded dealer
  # fan (with a small antialias margin), avoiding unused hand contours in the
  # download and keeping the GPU clip small on phones.
  bounded=np.zeros_like(mask)
  bounded[850-Y:940-Y,326-X:575-X]=mask[850-Y:940-Y,326-X:575-X]
  mask=bounded
  cs,_=cv2.findContours(mask,cv2.RETR_EXTERNAL,cv2.CHAIN_APPROX_SIMPLE)
  polygons=[(cv2.approxPolyDP(c,.65,True)[:,0,:]+[X,Y]).tolist() for c in cs if cv2.contourArea(c)>=2]
  frames.append(polygons)
  if seat=='dealer' and f in [24,28,32,36,40,44,48,51,52,56]:
   im=Image.fromarray(rgb);d=ImageDraw.Draw(im)
   for poly in polygons:d.line([(x-X,y-Y) for x,y in poly]+[(poly[0][0]-X,poly[0][1]-Y)],fill='#00ff99',width=1)
   d.text((3,3),f'frame {f}',fill='red');samples.append(im)
  f+=1
 tracks[seat]=frames
 metrics[seat]={'frames':f,'fps':cap.get(cv2.CAP_PROP_FPS),'sha256':hashlib.sha256(path.read_bytes()).hexdigest()}
 cap.release()
(ROOT/'public/dealer-hand-tracks.js').write_text('// Generated by review/2026-09-28-hand-occlusion/build-tracks.py.\n// Absolute source coordinates, 24 fps, only the dealer-card area.\nexport const DEALER_HAND_TRACKS = '+json.dumps(tracks,separators=(',',':'))+';\n')
(OUT/'measurements.json').write_text(json.dumps(metrics,indent=2)+'\n')
sheet=Image.new('RGB',(W*5,H*2),'#222')
for i,im in enumerate(samples):sheet.paste(im,((i%5)*W,(i//5)*H))
sheet.save(OUT/'source-contours.jpg',quality=92)
print(json.dumps({s:{**v,'points':sum(len(p) for f in tracks[s] for p in f)} for s,v in metrics.items()},indent=2))
