import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {calibrationPayload,validateContactTake} from '../../../../web/public/performance-contact.mjs';
const dir=path.dirname(fileURLToPath(import.meta.url));
const publicDir=path.resolve(dir,'../../../../web/public/review/astrid-table-v2');
const previousDir=path.resolve(publicDir,'../astrid-elevated-table');
const input=path.resolve(process.argv[2]??path.join(dir,'mask'));
const take=JSON.parse(fs.readFileSync(path.join(previousDir,'take.json')));
const mask=JSON.parse(fs.readFileSync(path.join(input,'manifest.json')));
const packed=fs.readFileSync(path.join(input,'actor-packed.mp4'));
const packedHash=createHash('sha256').update(packed).digest('hex');
if(mask.sourceSha256!==take.tracking.sourceSha256||mask.actorPackedSha256!==packedHash||JSON.stringify(mask.crop)!=='[560,0,960,760]'||mask.frameCount!==97||mask.fps!=='24/1')throw new Error('Mask source, geometry or frame clock differs from the tracked take');
take.id='astrid-table-v2-first-upcard-de1f90a9';
take.media.src='review/astrid-table-v2/actor-packed.mp4';
take.media.sha256=packedHash;
take.camera.placement.y=0;
take.camera.placement.framingScale=.85;
take.cameraApproval+=' Table-v2 derivative uses saved PlateCam; removes the old20px gameplay-only Y offset, preserves native actor scale1.';
take.calibrationSha256=createHash('sha256').update(calibrationPayload(take)).digest('hex');
const errors=validateContactTake(take);if(errors.length)throw new Error(errors.join('\n'));
fs.mkdirSync(publicDir,{recursive:true});
fs.writeFileSync(path.join(publicDir,'actor-packed.mp4'),packed);
fs.copyFileSync(path.join(input,'rest-0096-crop.png'),path.join(publicDir,'rest.png'));
fs.copyFileSync(path.join(input,'manifest.json'),path.join(publicDir,'mask-manifest.json'));
fs.writeFileSync(path.join(publicDir,'take.json'),JSON.stringify(take,null,2)+'\n');
console.log(JSON.stringify({id:take.id,media:take.media,placement:take.camera.placement,calibrationSha256:take.calibrationSha256}));
