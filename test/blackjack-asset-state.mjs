import assert from 'node:assert/strict';
import fs from 'node:fs';
import {shoePresentation} from '../web/public/blackjack-asset-state.mjs';
const full=shoePresentation({total:416,remaining:415,dealt:1,cutAfter:312,cutReached:false});
const half=shoePresentation({total:416,remaining:208,dealt:208,cutAfter:312,cutReached:false});
assert(full.hasCards);assert.equal(full.cutRemoved,false);assert(full.pusherZ<half.pusherZ);
const cut=shoePresentation({total:416,remaining:104,dealt:312,cutAfter:312,cutReached:true});
assert(cut.cutRemoved);assert.equal(cut.cutZ,0);
const empty=shoePresentation({total:416,remaining:0,dealt:416,cutAfter:312,cutReached:true});
assert.equal(empty.hasCards,false);assert.equal(empty.fraction,0);
assert.throws(()=>shoePresentation({total:416,remaining:400,dealt:1,cutAfter:312}),/Invalid/);
// Verify the actual exported binary, not a mocked object hierarchy.
const path=new URL('../web/public/assets/blackjack-3d/blackjack-table.glb',import.meta.url),buffer=fs.readFileSync(path);
assert.equal(buffer.toString('ascii',0,4),'glTF');assert.equal(buffer.readUInt32LE(4),2);
const length=buffer.readUInt32LE(12),gltf=JSON.parse(buffer.toString('utf8',20,20+length));
const byName=new Map(gltf.nodes.map(n=>[n.name,n]));
for(const name of ['Shoe_Outlet','Shoe_Pack','Shoe_Pusher','Shoe_CutCard','Shoe_FrontCard','Card_Template','Dealer_Cards','Discard_Landing'])assert(byName.has(name),`Missing ${name}`);
for(let i=1;i<=7;i++)assert(byName.has(`Seat_${String(i).padStart(2,'0')}_Card_Landing`));
const triangles=gltf.meshes.flatMap(m=>m.primitives).reduce((n,p)=>n+(gltf.accessors[p.indices]?.count??0)/3,0);
assert(triangles<90000,`Table geometry budget exceeded: ${triangles}`);
assert(gltf.materials.some(m=>m.name.startsWith('CardFace')));
assert(gltf.images.every(i=>Number.isInteger(i.bufferView)),'Textures must be embedded for handoff');
assert(buffer.length<8*1024*1024,'Table export size budget exceeded');
console.log(`Blackjack asset state: shoe lifecycle and exported node contract pass (${triangles} unique triangles, ${buffer.length} bytes).`);
