import test from 'node:test';
import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {randomUUID} from 'node:crypto';
import {createSqliteRouletteCommand} from '../web/games/roulette/storage.mjs';
import {ROOM} from '../web/games/roulette/room.mjs';

test('wallet, ledger and scoped room persist together; replay, restart and rollback preserve money',async t=>{
  const root=await mkdtemp(join(tmpdir(),'roulette-storage-')),path=join(root,'isolated.sqlite');let db=new DatabaseSync(path),calls=0;
  t.after(async()=>{db.close();await rm(root,{recursive:true,force:true});});
  db.exec(`CREATE TABLE players(id TEXT PRIMARY KEY,name TEXT,currency TEXT,balance NUMERIC);
    CREATE TABLE transactions(id INTEGER PRIMARY KEY,player_id TEXT,type TEXT,amount NUMERIC,currency TEXT,meta TEXT,at TEXT);
    INSERT INTO players VALUES ('a','Alice','USD',100),('b','Bob','EUR',500);`);
  const draw=context=>{calls++;return {...context,eventId:randomUUID(),occurredAt:new Date().toISOString(),outcome:{number:0,color:'green'}};};
  let run=createSqliteRouletteCommand({db,draw});
  const request={id:'a',op:'spin',requestId:randomUUID(),version:0,bets:[{id:'straight-0',amount:2},{id:'red',amount:5}]};
  const first=run(request);assert.equal(first.balance,165);assert.equal(first.round.net,65);
  assert.equal(run(request).replayed,true);assert.equal(calls,1);
  assert.equal(db.prepare('SELECT count(*) AS n FROM transactions').get().n,2);
  assert.equal(run({id:'b',op:'state'}).balance,500);assert.equal(run({id:'b',op:'state'}).version,0);
  assert.equal(run({id:'a',op:'state'},{room:{...ROOM,id:'second'}}).version,0);
  assert.equal(run({id:'a',op:'state'},{room:{...ROOM,operatorId:'other'}}).version,0);
  db.close();db=new DatabaseSync(path);run=createSqliteRouletteCommand({db,draw});
  assert.equal(run(request).round.id,first.round.id);assert.equal(calls,1);
  assert.equal(run({id:'a',op:'state'}).balance,165);
  db.exec("CREATE TRIGGER reject_ledger BEFORE INSERT ON transactions BEGIN SELECT RAISE(ABORT,'ledger unavailable'); END;");
  const next={...request,requestId:randomUUID(),version:1};
  assert.throws(()=>run(next),/ledger unavailable/);
  const restored=run({id:'a',op:'state'});assert.equal(restored.version,1);assert.equal(restored.balance,165);assert.equal(restored.rounds.length,1);
  db.exec('DROP TRIGGER reject_ledger');
  assert.equal(run(next).balance,230);
  db.prepare("UPDATE players SET currency='EUR' WHERE id='a'").run();
  assert.equal(run({id:'a',op:'state'}).rounds[0].currency,'USD');
  assert.throws(()=>run({...next,requestId:randomUUID()}),/room_changed/);
  const rows=db.prepare('SELECT amount,meta FROM transactions ORDER BY id').all();
  assert.deepEqual(rows.map(row=>row.amount),[-7,72,-7,72]);
  assert.equal(JSON.parse(rows[0].meta).roundId,first.round.id);
});
