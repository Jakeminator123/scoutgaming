test('SQL migration inspects complete private snapshots without changing the source and requires a writer freeze',async()=>{
  const fixture=await migrationFixture();try{
    await assert.rejects(inspectSqliteMigration({...fixture}),/writers/);
    const plan=await inspectSqliteMigration({...fixture,quiesced:true});
    assert.equal(plan.tables.length,31);assert.equal(plan.tables.find(row=>row.table==='transactions').rows[0].id,'41');
    assert.equal(plan.sources[0].sequences.find(row=>row.table==='transactions').seq,'80');
    assert.deepEqual((await inspectSqliteMigration({...fixture,quiesced:true})).sources,plan.sources);
  }finally{await fixture.cleanup();}
});

test('migration refuses active external wallets before writing the target',async()=>{
  const fixture=await migrationFixture();let queries=0;
  try{
    const db=new DatabaseSync(fixture.authPath);db.prepare('INSERT INTO api_keys(id,name,key,secret,scopes,wallet_url,created_at)VALUES(?,?,?,?,?,?,?)').run('fixture-external','Synthetic external','fixture-key','fixture-secret','["play"]','https://wallet.example.invalid','qa');db.close();
    const pool={async connect(){return{async query(){queries++;},release(){}};}};
    await assert.rejects(migrateSqliteToPostgres({pool,...fixture,quiesced:true}),/external wallets/);
    // Best-effort rollback is harmless; no INSERT/schema statement can be sent.
    assert.ok(queries<=1);
  }finally{await fixture.cleanup();}
});

test('restore rejects missing or duplicate identity sequences before connecting',async()=>{
  const fixture=await migrationFixture(),hash=value=>createHash('sha256').update(value).digest('hex');
  try{
    const schemaSql=(await readFile(new URL('../ops/neon-game/product-schema.sql',import.meta.url),'utf8')).replace(/\r\n/g,'\n');
    const tables=[...schemaSql.matchAll(/CREATE TABLE (croupier_game|croupier_auth)\.([a-z_]+)\s*\(/g)].map(([,schema,table])=>({schema,table,columns:[],rows:[],count:0,sha256:hash('[]')}));
    const sequences=[['croupier_game','transactions'],['croupier_game','partner_rounds'],['croupier_game','player_admin_events'],['croupier_auth','users']].map(([schema,table])=>({schema,table,lastValue:'1',isCalled:false}));
    const source=join(fixture.directory,'broken-backup.json'),pool={connect(){throw Error('Must validate before connecting');}};
    for(const broken of [sequences.slice(1),[sequences[0],...sequences.slice(0,3)]]){
      const payload={schema:'croupier-postgres-backup-v1',schemaSql,schemaChecksum:hash(schemaSql),tables,sequences:broken};
      await writeFile(source,JSON.stringify({payload,sha256:hash(JSON.stringify(payload))}));
      await assert.rejects(restorePostgresBackup({pool,source,quiesced:true}),/incomplete backup sequences/);
    }
  }finally{await fixture.cleanup();}
});

test('real isolated PostgreSQL imports full history, refuses overwrite, and restores SQL backup into empty schemas', {skip:!process.env.CROUPIER_POSTGRES_MIGRATION_QA_CONFIG},async()=>{
  const fixture=await migrationFixture(),config=JSON.parse(await readFile(process.env.CROUPIER_POSTGRES_MIGRATION_QA_CONFIG,'utf8'));
  const store=createPostgresStore({connectionString:config.databaseUrl});
  try {
    const current=(await store.pool.query('SELECT current_database() AS name')).rows[0].name;assert.equal(current,'croupier_game_qa');
    const result=await migrateSqliteToPostgres({pool:store.pool,...fixture,quiesced:true});assert.equal(result.tables.length,31);
    assert.equal((await store.db.prepare('SELECT balance FROM players WHERE id=?').get('qa-migrated')).balance,1234.5);
    assert.equal((await store.boDb.prepare('SELECT epoch FROM bo_auth_epochs WHERE user_id=?').get(11)).epoch,7);
    const inserted=(await store.pool.query("INSERT INTO croupier_game.transactions(player_id,type,amount,currency,at)VALUES('qa-migrated','qa',0,'USD','qa')RETURNING id")).rows[0].id;assert.equal(inserted,'81');
    await assert.rejects(migrateSqliteToPostgres({pool:store.pool,...fixture,quiesced:true}),/already completed/);
    const backupFile=join(fixture.directory,'postgres-private.json');const exported=await exportPostgresBackup({pool:store.pool,destination:backupFile});
    await assert.rejects(restorePostgresBackup({pool:store.pool,source:backupFile,quiesced:true}),/empty schemas/);
    // Only this dedicated synthetic QA database is reset; never a zone/live DB.
    await store.pool.query('DROP SCHEMA croupier_game CASCADE; DROP SCHEMA croupier_auth CASCADE;');
    const restored=await restorePostgresBackup({pool:store.pool,source:backupFile,quiesced:true});assert.equal(restored.sha256,exported.sha256);
    assert.equal((await store.db.prepare('SELECT COUNT(*) AS n FROM transactions').get()).n,2);
  }finally{await store.close();await fixture.cleanup();}
});
